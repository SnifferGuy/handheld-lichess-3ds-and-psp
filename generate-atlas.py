"""Build the shared artwork with Pillow 13.0.0, resvg-py 0.3.3, and tex3ds."""
import argparse
import io
from pathlib import Path
import subprocess

from PIL import Image, ImageDraw, ImageFont
import resvg_py

ROOT = Path(__file__).resolve().parent
WIDTH, HEIGHT = 256, 512


def launcher_icons():
    assets = ROOT / "assets"
    knight_svg = assets / "cburnett" / "wN.svg"
    scale = 4
    for file, width, height in (("icon-3ds.png", 48, 48), ("icon-psp.png", 144, 80)):
        icon = Image.new("RGBA", (width * scale, height * scale), "#302E2B")
        board_size = (height - 6) * scale
        left = (icon.width - board_size) // 2
        top = (icon.height - board_size) // 2
        board = Image.new("RGBA", (board_size, board_size), "#EBECD0")
        draw = ImageDraw.Draw(board)
        half = board_size // 2
        draw.rectangle((half, 0, board_size, half - 1), fill="#739552")
        draw.rectangle((0, half, half - 1, board_size), fill="#739552")
        piece_size = board_size * 9 // 10
        raster = resvg_py.svg_to_bytes(svg_path=str(knight_svg), width=piece_size, height=piece_size)
        knight = Image.open(io.BytesIO(raster)).convert("RGBA")
        origin = (board_size - piece_size) // 2
        board.alpha_composite(knight, (origin, origin))
        mask = Image.new("L", board.size)
        ImageDraw.Draw(mask).rounded_rectangle((0, 0, board_size - 1, board_size - 1), radius=4*scale, fill=255)
        icon.paste(board, (left, top), mask)
        icon.resize((width, height), Image.Resampling.LANCZOS).save(assets / file)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--tex3ds", default="tex3ds")
    parser.add_argument("--icons-only", action="store_true")
    options = parser.parse_args()
    launcher_icons()
    if options.icons_only:
        return
    atlas = Image.new("RGBA", (WIDTH, HEIGHT))
    x, y, shelf = 1, 1, 0

    def pack(bitmap, advance=0, dx=0, dy=0):
        nonlocal x, y, shelf
        w, h = bitmap.size
        if not w or not h:
            return (0, 0, 0, 0, advance, dx, dy)
        if x + w >= WIDTH:
            x, y, shelf = 1, y + shelf + 1, 0
        if y + h >= HEIGHT:
            raise ValueError("Artwork exceeds the atlas")
        atlas.paste(bitmap, (x, y))
        sprite = (x, y, w, h, advance, dx, dy)
        x += w + 1
        shelf = max(shelf, h)
        return sprite

    def cpp(values):
        return "{" + ",".join(map(str, values)) + "}"

    pieces = []
    for size in (28, 32):
        sprites = []
        for color in "wb":
            for piece in "PNBRQK":
                svg = ROOT / "assets" / "cburnett" / f"{color}{piece}.svg"
                data = resvg_py.svg_to_bytes(svg_path=str(svg), width=size-2, height=size-2)
                sprites.append(pack(Image.open(io.BytesIO(data)).convert("RGBA"), dx=1, dy=1))
        pieces.append(sprites)

    fonts = []
    for size in (10, 14, 22, 18):
        font = ImageFont.truetype(str(ROOT / "assets" / "NotoSans.ttf"), size)
        glyphs = []
        for code in range(32, 127):
            char = chr(code)
            left, top, right, bottom = font.getbbox(char, anchor="ls")
            glyph = Image.new("RGBA", (right-left, bottom-top))
            if glyph.height:
                ImageDraw.Draw(glyph).text((-left, -top), char, font=font, anchor="ls", fill="white")
            glyphs.append(pack(glyph, max(1, round(font.getlength(char))), left, size+top))
        fonts.append(glyphs)

    build = ROOT / "build"
    build.mkdir(exist_ok=True)
    png, t3x = build / "screen-atlas.png", build / "screen-atlas.t3x"
    atlas.save(png)
    subprocess.run([options.tex3ds, "-f", "rgba8", "-z", "lz11", "-o", str(t3x), str(png)], check=True)
    with (ROOT / "screen_atlas.hpp").open("w", encoding="ascii", newline="\n") as out:
        out.write("// Generated by generate-atlas.py.\n#pragma once\n#include \"screen.hpp\"\n")
        out.write("namespace handheld::art {\nconstexpr int width=256, height=512;\n")
        for name, table in (("pieces", pieces), ("fonts", fonts)):
            out.write(f"constexpr Sprite {name}[{len(table)}][{len(table[0])}]={{\n")
            for row in table:
                out.write("{" + ",\n".join(cpp(sprite) for sprite in row) + "},\n")
            out.write("};\n")
        for directive, name, data in (
            ("#ifdef __3DS__", "texture", t3x.read_bytes()),
            ("#else", "pixels", atlas.tobytes()),
        ):
            out.write(f"{directive}\ninline constexpr unsigned char {name}[]={{\n")
            for start in range(0, len(data), 32):
                out.write(",".join(map(str, data[start:start+32])) + ",\n")
            out.write("};\n")
        out.write("#endif\n}\n")


if __name__ == "__main__":
    main()
